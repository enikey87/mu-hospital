const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.SITE_URL || 'http://127.0.0.1:5188/mu-hospital/';
const digits = value => value.replace(/\D/g, '');

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || undefined, args: ['--no-sandbox'] });
  const report = [];
  try {
    for (const width of [1440, 1200, 768, 390, 320]) {
      const page = await browser.newPage({ viewport: { width, height: 1000 } });
      const errors = [], failedResources = [], writes = [];
      page.on('pageerror', e => errors.push(e.message));
      page.on('request', request => { if (!['GET', 'HEAD'].includes(request.method())) writes.push(request.url()); });
      page.on('response', response => { if (/\/(assets|images|fonts)\//.test(response.url()) && response.status() >= 400) failedResources.push(response.url()); });
      const layout = async state => {
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width, state);
        const nodes = page.locator('main h1, main h2, main h3, .ug9, .ug9 table, .sol-franchise section, .header__inner, .sol-header__inner');
        assert.ok(await nodes.count(), state);
        const overflow = await nodes.evaluateAll(nodes => nodes.filter(n => { const r = n.getBoundingClientRect(); return r.width && (r.left < -1 || r.right > innerWidth + 1 || n.scrollWidth > n.clientWidth + 1); }).map(n => [n.tagName, n.className]));
        assert.deepEqual(overflow, [], state);
      };
      await page.goto(base + '#/urinatech', { waitUntil: 'networkidle' });
      await page.locator('.hero a[href="#/urinatech?section=ug9"]').click();
      await page.waitForFunction(() => document.getElementById('ug9').getBoundingClientRect().top >= 0 && document.getElementById('ug9').getBoundingClientRect().top < 200);
      assert.equal(await page.locator('.ug9-benefit').count(), 9);
      assert.equal(await page.locator('.ug9 table').last().getByText('Не проходит', { exact: true }).count(), 3);
      await layout('ug9');
      const offer = page.getByRole('button', { name: 'Включить УГ-9 в спецификацию', exact: true });
      await offer.click();
      assert.equal(digits(await page.locator('.cart-total').innerText()), '12460');
      await page.locator('.cart-close').click();
      const card = page.locator('.product-card').filter({ has: page.getByRole('heading', { name: 'Анальное кольцо УГ-9', exact: true, level: 3 }) });
      await card.getByRole('button', { name: 'В спецификацию', exact: true }).click();
      assert.equal(await page.locator('.cart-item .qty').innerText(), '2');
      assert.equal(digits(await page.locator('.cart-total').innerText()), '24920');
      await page.locator('.cart-item').getByRole('button', { name: '−', exact: true }).click();
      await page.getByRole('button', { name: 'Сформировать спецификацию', exact: true }).click();
      await page.getByText('Спецификация сформирована', { exact: true }).waitFor();
      await page.locator('.cart-order').getByRole('button', { name: 'Закрыть', exact: true }).click();
      await offer.click();
      assert.equal(await page.locator('.cart-item .qty').innerText(), '1');
      await page.locator('.cart-item').getByRole('button', { name: '−', exact: true }).click();
      await page.getByText('Корзина пуста.', { exact: false }).waitFor();
      await page.locator('.cart-close').click();
      await page.goto(base + '#/solnyshko/kalofores', { waitUntil: 'networkidle' });
      await page.locator('.sol-detail__hero a[href="#/solnyshko/franchise"]').click();
      await page.getByRole('heading', { level: 1, name: 'Франшиза калофореза', exact: true }).waitFor();
      assert.match(await page.title(), /Франшиза.*Калофорез/);
      await page.locator('.sol-franchise img').evaluate(n => n.decode());
      await layout('franchise');
      await page.getByRole('link', { name: 'Рассчитать комплект ↗', exact: true }).click();
      const city = page.getByLabel('Город открытия');
      const rooms = page.getByLabel('Количество кабинетов');
      const submit = page.getByRole('button', { name: 'Сформировать расчёт', exact: true });
      assert.equal(await rooms.locator('option').count(), 3);
      assert.equal(digits(await page.locator('output').innerText()), '124600');
      await submit.click(); assert.equal(await city.evaluate(n => n.validity.valueMissing), true);
      await city.fill('Я'); await submit.click(); assert.equal(await city.evaluate(n => n.checkValidity()), false);
      await city.fill('  '); await submit.click(); await page.getByRole('alert').waitFor();
      assert.equal(await page.locator('.sol-franchise__result').count(), 0);
      await city.fill('  Тюмень  '); assert.equal(await page.getByRole('alert').count(), 0);
      await rooms.selectOption('3');
      assert.equal(digits(await page.locator('output').innerText()), '373800');
      await submit.click();
      const result = page.locator('.sol-franchise__result');
      await result.getByRole('heading', { name: 'Предварительный расчёт готов', exact: true }).waitFor();
      assert.equal(await result.locator('b').innerText(), 'Тюмень');
      assert.match(await result.innerText(), /Кабинетов: 3 · аппаратов М2: 3/);
      assert.equal(digits(await result.locator('.sol-franchise__total').innerText()), '373800');
      await layout('franchise-result');
      await result.getByRole('button', { name: 'Новый расчёт', exact: true }).click();
      assert.equal(await city.inputValue(), ''); assert.equal(await rooms.inputValue(), '1');
      assert.equal(digits(await page.locator('output').innerText()), '124600');
      await page.reload({ waitUntil: 'networkidle' });
      assert.equal(await city.inputValue(), '');
      await page.locator('.sol-header__brand').click();
      await page.locator('.sol-hero h1').waitFor();
      assert.equal(new URL(page.url()).hash, '#/');
      assert.equal(await page.locator('#ug9, .sol-franchise').count(), 0);
      await page.goBack({ waitUntil: 'networkidle' });
      await page.getByRole('heading', { level: 1, name: 'Франшиза калофореза', exact: true }).waitFor();
      assert.deepEqual(errors, []); assert.deepEqual(failedResources, []); assert.deepEqual(writes, []);
      report.push({ width, base, states: ['ug9-cart-catalog-complete-restart-empty', 'franchise-validation-three-cabinets-reset-reload-history'], errors, failedResources, writes });
      await page.close(); console.log('PASS', width);
    }
    fs.writeFileSync(process.env.REPORT_PATH || '/tmp/mu-new-offers-browser.json', JSON.stringify(report, null, 2) + '\n');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
