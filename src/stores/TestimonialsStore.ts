export class TestimonialsStore {
  reviews: Review[] = BASE_REVIEWS.map((r, i) => ({ ...r, id: i + 1 }));
  private nextId = BASE_REVIEWS.length + 1;
  loading = false;

  constructor() {
    makeAutoObservable(this);
  }

  get hasMore(): boolean {
    return this.nextId <= BASE_REVIEWS.length + EXTRA_REVIEWS.length;
  }

  loadMore(): void {
    if (!this.hasMore || this.loading) return;
    this.loading = true;
    setTimeout(() => {
      const next = EXTRA_REVIEWS[this.nextId - BASE_REVIEWS.length - 1];
      if (next) {
        this.reviews.push({ ...next, id: this.nextId });
        this.nextId += 1;
      }
      this.loading = false;
    }, 900);
  }
}
